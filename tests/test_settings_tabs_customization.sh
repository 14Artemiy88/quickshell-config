#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WIDGET="$ROOT/components/settings/SettingsWidget.qml"
NAV="$ROOT/components/settings/SettingsNavigation.qml"
REGISTRY="$ROOT/js/settings/SettingsPageRegistry.js"
WINDOW="$ROOT/components/settings/sections/SettingsWindowSection.qml"
CONFIG="$ROOT/Config.qml"
PERSIST="$ROOT/js/settings/SettingsPersistence.js"
APPLY="$ROOT/js/settings/SettingsApplyCore.js"
RESETS="$ROOT/js/settings/SettingsResets.js"
SETTINGS="$ROOT/Settings.qml"
DEFAULTS="$ROOT/js/settings/SettingsDefaults.js"

! grep -Fq 'property var settingsTabOrder:' "$CONFIG"
grep -Fq 'property var settingsTabLabels:' "$CONFIG"
! grep -Fq 'settingsTabOrder:' "$DEFAULTS"
! grep -Fq 'Config.settingsTabOrder' "$ROOT/components/settings/SettingsNavigationController.qml"
! grep -Fq 'settingsTabOrderNormalized' "$WIDGET"
grep -Fq 'managedKeys.push("settingsTabOrder")' "$PERSIST" || grep -Fq 'managedKeys.indexOf("settingsTabOrder")' "$PERSIST"
! grep -Fq 'Config.settingsTabOrder' "$APPLY"
! grep -Fq 'Config.settingsTabOrder' "$RESETS"
grep -Fq 'settingsNavigationOrder: cloneValue(owner && typeof owner.normalizeSettingsNavigationOrder' "$PERSIST"
grep -Fq 'settingsTabLabels: cloneValue(config.settingsTabLabels' "$PERSIST"
grep -Fq 'Config.settingsNavigationOrder = normalizeNavigationOrderForOwner(owner, o.settingsNavigationOrder)' "$APPLY"
grep -Fq 'var normalizedSettingsLabels = normalizeSettingsTabLabels(o.settingsTabLabels, Config.settingsTabLabels)' "$APPLY"
grep -Fq 'Config.settingsTabLabels = normalizedSettingsLabels' "$APPLY"
grep -Fq '"settingsNavigationOrder", "settingsTabLabels"' "$RESETS"
grep -Eq '"settingsNavigationOrder"[[:space:]]*,[[:space:]]*"settingsTabLabels"' "$SETTINGS"
grep -Fq 'settingsNavigationOrder: ({' "$DEFAULTS"
grep -Fq 'settingsTabLabels:' "$DEFAULTS"

grep -Fq '{ id: "settingsWindow", saveScope: "settingsWindow", subTabs: ["Интерфейс", "Окно настроек", "Вкладки"] }' "$REGISTRY"
grep -Fq 'readonly property var settingsNavigationItems:' "$WIDGET"
grep -Fq 'function moveSettingsTab(id, delta)' "$WIDGET"
grep -Fq 'function moveSettingsTabWithinGroup(groupId, id, delta)' "$WIDGET"
grep -Fq 'function settingsTabCanMoveWithinGroup(groupId, id, delta)' "$WIDGET"
grep -Fq 'function setSettingsTabLabel(id, value)' "$WIDGET"
grep -Fq 'navigationGroups: root.settingsNavigationGroups' "$WIDGET"
grep -Fq 'model: root.navigationGroups' "$NAV"
grep -Fq 'text: "Вкладки панели настроек"' "$WINDOW"
grep -Fq 'model: host ? host.settingsNavigationGroups : []' "$WINDOW"
grep -Fq 'heading: groupData.label' "$WINDOW"
grep -Fq 'model: settingsNavigationPageGroup.groupData.items' "$WINDOW"
grep -Fq 'visible: host && host.currentPageId === "settingsWindow" && host.currentPageSubTabIndex === 2' "$WINDOW"
grep -Fq 'host.setSettingsTabLabel(modelData.id, text)' "$WINDOW"
grep -Fq 'host.moveSettingsTabWithinGroupTo(' "$WINDOW"
grep -Fq 'function moveSettingsTabWithinGroupTo(groupId, id, toIndex)' "$WIDGET"
grep -Fq 'внутри своей рамки' "$WINDOW"

echo 'settings sidebar labels/order customization and persistence: OK'
